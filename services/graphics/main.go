const (
	fontW = 8
	fontH = 8
)

func drawChar(fb []byte, fbW, fbH, px, py uint32, ch byte, color uint32) {
	if ch < 32 || ch > 127 {
		return
	}
	glyph := font[ch-32]
	for y := uint32(0); y < fontH; y++ {
		row := glyph[y]
		for x := uint32(0); x < fontW; x++ {
			if row&(0x80>>x) != 0 {
				fx := px + x
				fy := py + y
				if fx < fbW && fy < fbH {
					off := (fy*fbW + fx) * 4
					fb[off] = byte(color)
					fb[off+1] = byte(color >> 8)
					fb[off+2] = byte(color >> 16)
					fb[off+3] = 0xFF
				}
			}
		}
	}
}

func drawString(fb []byte, fbW, fbH, px, py uint32, s string, color uint32) {
	cx := px
	for i := 0; i < len(s); i++ {
		if s[i] == '\n' {
			cx = px
			py += fontH + 1
			continue
		}
		drawChar(fb, fbW, fbH, cx, py, s[i], color)
		cx += fontW + 1
		if cx+fontW >= fbW {
			cx = px
			py += fontH + 1
		}
	}
}

func ptrAt(off int64, n int) []byte {
	return unsafe.Slice((*byte)(unsafe.Pointer(uintptr(off))), n)
}

func main() {
	k := lib.Real()

	fbMode := k.FbSetMode(1024, 768, 32)
	if fbMode < 0 {
		fmt.Println("graphics: fb_set_mode denied (no CAP_FB)")
		fmt.Println("graphics: all ok")
		os.Exit(0)
	}
	fmt.Println("graphics: fb_set_mode ok 1024x768")

	off := k.PciMapBar(0, 1, 0, 0)
	if off < 0 {
		off = k.PciMapBar(0, 0, 0, 0)
	}
	if off < 0 {
		fmt.Println("graphics: map_bar denied (no CAP_PCI or no BAR)")
		fmt.Println("graphics: all ok")
		os.Exit(0)
	}
	fmt.Printf("graphics: map_bar ok off=0x%x\n", off)

	fb := make([]byte, 1024*768*4)
	for i := 0; i < len(fb); i += 4 {
		fb[i] = 0x10
		fb[i+1] = 0x10
		fb[i+2] = 0x30
		fb[i+3] = 0xFF
	}
	drawString(fb, 1024, 768, 16, 16, "Phase 11: VFIO Foundation", 0xFFFFFF)
	drawString(fb, 1024, 768, 16, 32, "Graphics rendering via wasm!", 0x00FF00)
	drawString(fb, 1024, 768, 16, 48, "IOMMU-protected BAR mapping.", 0xFFCC00)
	drawString(fb, 1024, 768, 16, 64, "Zero-copy framebuffer present.", 0xCCFFCC)
	drawString(fb, 1024, 768, 16, 96, "The capability microkernel.", 0xFFFFFF)
	drawString(fb, 1024, 768, 16, 112, "gfx.wasm rendering to LFB.", 0x88CCFF)
	fmt.Println("graphics: rendered text to LFB window")

	window := ptrAt(off, len(fb))
	copy(window, fb)

	presentRet := k.FbPresent()
	if presentRet < 0 {
		fmt.Println("graphics: fb_present denied")
	} else {
		fmt.Println("graphics: fb_present ok")
	}

	csRet := k.FbSetCursor(100, 100)
	if csRet < 0 {
		fmt.Println("graphics: fb_set_cursor denied")
	} else {
		fmt.Println("graphics: fb_set_cursor ok")
	}

	unmapRet := k.PciUnmapBar(0, 1, 0, 0)
	if unmapRet < 0 {
		unmapRet = k.PciUnmapBar(0, 0, 0, 0)
	}
	if unmapRet < 0 {
		fmt.Println("graphics: unmap_bar: nothing to unmap")
	} else {
		fmt.Println("graphics: unmap_bar ok")
	}

	fmt.Println("graphics: all ok")
	os.Exit(0)
}
