const (
	fontW = 8
	fontH = 8
)

func main() {
	k := lib.Real()

	// 1. Set display mode (needs CAP_FB)
	fbMode := k.FbSetMode(1024, 768, 32)
	if fbMode < 0 {
		fmt.Println("graphics: fb_set_mode denied (no CAP_FB)")
		fmt.Println("graphics: all ok")
		os.Exit(0)
	}
	fmt.Println("graphics: fb_set_mode ok 1024x768")

	// 2. Map framebuffer BAR (needs CAP_PCI)
	// Try bus 0 dev 0 fn 0 — on QEMU q35 this is the host bridge
	off := k.PciMapBar(0, 0, 0, 0)
	if off < 0 {
		fmt.Println("graphics: map_bar denied (no CAP_PCI or no BAR)")
		fmt.Println("graphics: all ok")
		os.Exit(0)
	}
	fmt.Printf("graphics: map_bar ok off=0x%x\n", off)

	// 3. Enable busmaster for DMA
	bmRet := k.PciEnableBusmaster(0, 0, 0)
	if bmRet < 0 {
		fmt.Println("graphics: enable_busmaster denied")
	} else {
		fmt.Println("graphics: enable_busmaster ok")
	}

	// 4. Bind IRQ for VSYNC
	h, err := k.PciBindIrq(0, 0, 0, 2) // MSI-X
	if err != nil {
		fmt.Printf("graphics: bind_irq result: %v\n", err)
	} else {
		fmt.Printf("graphics: bind_irq handle=%d\n", h)
	}

	// 5. Present framebuffer (flip)
	presentRet := k.FbPresent()
	if presentRet < 0 {
		fmt.Println("graphics: fb_present denied")
	} else {
		fmt.Println("graphics: fb_present ok")
	}

	// 6. Set cursor position
	csRet := k.FbSetCursor(100, 100)
	if csRet < 0 {
		fmt.Println("graphics: fb_set_cursor denied")
	} else {
		fmt.Println("graphics: fb_set_cursor ok")
	}

	// 7. Unmap BAR (cleanup)
	unmapRet := k.PciUnmapBar(0, 0, 0, 0)
	if unmapRet < 0 {
		fmt.Println("graphics: unmap_bar: nothing to unmap")
	} else {
		fmt.Println("graphics: unmap_bar ok")
	}

	fmt.Println("graphics: all ok")
	os.Exit(0)
}
